"""The results table: one row per batch run, every number computed from the batch records.

Validity and hub totals count feasible plans (a room over 100 m² has no valid
design); cable, bends, crossings, overlap and J count valid plans; runtime
counts every plan.
"""
import json
import pathlib

from loopwright.batch import p50_p95

FEASIBLE = ("valid", "invalid", "crash")


def load_rows(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def summarize(rows):
    feasible = [r for r in rows if r["status"] in FEASIBLE]
    solved = [r for r in feasible if r["status"] != "crash"]
    valid = [r for r in rows if r["status"] == "valid"]
    p50, p95 = p50_p95([r["runtime_s"] for r in rows]) if rows else (0.0, 0.0)
    return {
        "plans": len(rows), "feasible": len(feasible), "valid": len(valid),
        "valid_pct": round(100 * len(valid) / len(feasible), 1) if feasible else 0.0,
        "hubs": sum(r["hubs"] for r in solved),
        "lower_bound": sum(r["hub_lower_bound"] for r in solved),
        "greedy": sum(r["hubs_greedy"] for r in solved if r.get("hubs_greedy") is not None),
        "above_bound": sum(1 for r in solved if r["hubs"] > r["hub_lower_bound"]),
        "length_m": round(sum(r["length_m"] for r in valid), 1),
        "bends": sum(r["bends"] for r in valid),
        "crossings": sum(r["crossings"] for r in valid),
        "overlap_m": round(sum(r["overlap_m"] for r in valid), 1),
        "J": round(sum(r["J"] for r in valid), 1),
        "p50_s": p50, "p95_s": p95,
    }


def render_results(named):
    """named: {run name: summarize(rows)}, in display order."""
    lines = ["# Results", "",
             "Generated by `loopwright results` from batch records. Validity and hubs count feasible plans; "
             "cable, bends, crossings, overlap and J count valid plans; runtime counts every plan.", "",
             "| Run | Plans | Feasible | Valid | Hubs | Lower bound | Greedy | Above bound | Cable m | Bends "
             "| Crossings | Overlap m | J | p50 s | p95 s |",
             "|---|" + "---:|" * 14]
    for name, s in named.items():
        lines.append(f"| {name} | {s['plans']:,} | {s['feasible']:,} | {s['valid']:,} ({s['valid_pct']:.1f}%) "
                     f"| {s['hubs']:,} | {s['lower_bound']:,} | {s['greedy']:,} | {s['above_bound']:,} "
                     f"| {s['length_m']:,.1f} | {s['bends']:,} | {s['crossings']:,} | {s['overlap_m']:,.1f} "
                     f"| {s['J']:,.1f} | {s['p50_s']:.2f} | {s['p95_s']:.2f} |")
    return "\n".join(lines) + "\n"


def results_file(paths):
    return render_results({pathlib.Path(p).stem: summarize(load_rows(p)) for p in paths})
